// Generates supabase/seed.sql from the starter catalog in src/data/catalog.ts.
// Run with:  node scripts/generate-seed.ts   (Node 23.6+ runs TypeScript directly)
import { writeFileSync } from 'node:fs'
import { categories, products, testimonials } from '../src/data/catalog.ts'

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'number' || typeof v === 'boolean') return String(v)
  if (Array.isArray(v)) return v.length ? `array[${v.map(q).join(', ')}]::text[]` : `'{}'::text[]`
  return `'${String(v).replace(/'/g, "''")}'`
}

const lines: string[] = [
  '-- Starter data for Nirmal LifeCare. Generated by scripts/generate-seed.ts — safe to re-run.',
  '',
  'insert into public.categories (slug, name, short, form, description, sort_order) values',
  categories.map((c, i) => `  (${[c.slug, c.name, c.short, c.form, c.description].map(q).join(', ')}, ${i})`).join(',\n'),
  'on conflict (slug) do update set name = excluded.name, short = excluded.short, form = excluded.form, description = excluded.description, sort_order = excluded.sort_order;',
  '',
  'insert into public.products (slug, name, category, strength, pack, unit, composition, therapy, packaging, price, moq, featured) values',
  products
    .map((p) => `  (${[p.slug, p.name, p.category, p.strength, p.pack, p.unit, p.composition, p.therapy, p.packaging, p.price, p.moq ?? null, !!p.featured].map(q).join(', ')})`)
    .join(',\n'),
  'on conflict (slug) do nothing;',
  '',
  '-- Placeholder testimonials from the mockup; replace with real buyer feedback.',
  'insert into public.testimonials (name, role, initials, rating, date, topic, text)',
  'select * from (values',
  testimonials.map((t) => `  (${[t.name, t.role, t.initials, t.rating, t.date, t.topic, t.text].map(q).join(', ')})`).join(',\n'),
  ') as v(name, role, initials, rating, date, topic, text)',
  'where not exists (select 1 from public.testimonials);',
  '',
]

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), lines.join('\n'))
console.log(`seed.sql written: ${categories.length} categories, ${products.length} products, ${testimonials.length} testimonials`)
